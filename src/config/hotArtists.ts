export interface HotArtist {
  name: string
  pinyin: string
  abbr: string
}

export const HOT_ARTISTS: HotArtist[] = RAW.trim().split('\n').map(line => {
  const [name, pinyin, abbr] = line.trim().split('|')
  return { name, pinyin, abbr }
})

/** 输入纯字母时按 全拼/首字母 匹配热门歌手（exact > 前缀 > 包含） */
export const matchHotArtists = (input: string, limit = 6): HotArtist[] => {
  const q = input.toLowerCase().trim()
  if (!q || !/^[a-z]+$/.test(q)) return []
  const scored: Array<{ artist: HotArtist, score: number }> = []
  for (const artist of HOT_ARTISTS) {
    let score = 0
    if (artist.pinyin === q) score = 100
    else if (artist.abbr === q) score = 95
    else if (artist.pinyin.startsWith(q)) score = 70 + q.length
    else if (q.length >= 2 && artist.abbr.startsWith(q)) score = 60 + q.length
    else if (q.length >= 4 && artist.pinyin.includes(q)) score = 30 + q.length
    if (score > 0) scored.push({ artist, score })
  }
  return scored.sort((a, b) => b.score - a.score || a.artist.pinyin.length - b.artist.pinyin.length).slice(0, limit).map(item => item.artist)
}
